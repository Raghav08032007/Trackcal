"""Merge every translation table in this folder into src/lib/i18n/messages/<code>.json (one file per language, keys sorted).

    backend/.venv/Scripts/python frontend/web/scripts/i18n/build.py

Each table module defines LANGS (column order) and T: {English text: [one translation per language]}. A translation is a string, or
a dict of plural forms (zero/one/two/few/many/other). The same English text in two tables must agree, or the build stops."""
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / 'src' / 'lib' / 'i18n' / 'messages'


def main():
    merged, offline_keys = {}, []
    for path in sorted(HERE.glob('*.py')):
        if path.name == 'build.py':
            continue
        spec = importlib.util.spec_from_file_location(path.stem, path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        offline_keys += getattr(module, 'OFFLINE_KEYS', [])
        for key, row in module.T.items():
            assert len(row) == len(module.LANGS), f'{path.name}: "{key}" has {len(row)} translations for {len(module.LANGS)} languages'
            for code, value in zip(module.LANGS, row):
                catalog = merged.setdefault(code, {})
                assert key not in catalog or catalog[key] == value, f'{path.name}: "{key}" in {code} differs from another table'
                catalog[key] = value
    OUT.mkdir(parents=True, exist_ok=True)
    for code, catalog in merged.items():
        (OUT / f'{code}.json').write_text(json.dumps(dict(sorted(catalog.items())), ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
        print(code, len(catalog))
    write_offline(merged, offline_keys)


OFFLINE_JS = """/* Generated by scripts/i18n/build.py from the translation tables: do not edit. Translates the offline journal. */
"use strict";
const OFFLINE_TEXT = __TABLE__;
const offlineLocale = (() => { let saved = null; try { saved = localStorage.getItem("trackcal:locale"); } catch { /* storage unavailable */ }
  if (saved === "en" || OFFLINE_TEXT[saved]) return saved;
  for (const tag of [...(navigator.languages || []), navigator.language]) { const base = (tag || "").toLowerCase().split("-")[0]; if (base === "en" || OFFLINE_TEXT[base]) return base; }
  return "en"; })();
const offlineCatalog = OFFLINE_TEXT[offlineLocale] || {};
/** The offline page's t(): English text in, this device's language out, {name} values filled in. */
function offlineT(text, values = {}) { let out = offlineCatalog[text] || text; for (const [k, v] of Object.entries(values)) out = out.split(`{${k}}`).join(String(v)); return out; }
document.documentElement.lang = offlineLocale; document.documentElement.dir = offlineLocale === "ar" ? "rtl" : "ltr"; document.title = offlineT(document.title);
for (const el of document.querySelectorAll("[aria-label]")) el.setAttribute("aria-label", offlineT(el.getAttribute("aria-label")));
{ const walk = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT); let node;
  while ((node = walk.nextNode())) { const text = node.textContent.trim(); if (text && offlineCatalog[text]) node.textContent = node.textContent.replace(text, offlineCatalog[text]); } }
"""


def write_offline(merged, keys):
    """The offline journal runs with no app bundle, so it gets its own small dictionary next to it (cached by the service worker)."""
    missing = [f'{code}: {k}' for code, catalog in merged.items() for k in keys if k not in catalog]
    assert not missing, f'offline texts without a translation: {missing[:5]}'
    table = {code: {k: catalog[k] for k in keys} for code, catalog in sorted(merged.items())}
    js = OFFLINE_JS.replace('__TABLE__', json.dumps(table, ensure_ascii=False, separators=(',', ':')))
    (HERE.parents[1] / 'public' / 'offline-i18n.js').write_text(js, encoding='utf-8')
    print('offline', len(keys))


if __name__ == '__main__':
    main()
