# French typography: a narrow no-break space before ? ! : ; and inside « » (so a sign never starts a new line).
import re as _re
def _fr(s):
    s = _re.sub(r' ([?!:;])', ' \\1', s)
    return s.replace('« ', '« ').replace(' »', ' »')
